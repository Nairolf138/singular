def _bounded_trait_value(raw: str) -> float:
    """Parse a psyche trait override constrained to ``[0, 1]``."""

    try:
        value = float(raw)
    except (TypeError, ValueError) as exc:
        raise argparse.ArgumentTypeError("doit être un nombre entre 0 et 1") from exc
    if value < 0.0 or value > 1.0:
        raise argparse.ArgumentTypeError("doit être compris entre 0 et 1")
    return value


def _extract_talk_life_alias(argv: list[str] | None) -> str | None:
    """Extract ``talk --life/--live`` value from raw argv when present."""

    if not argv:
        return None

    try:
        talk_index = argv.index("talk")
    except ValueError:
        return None

    tokens = argv[talk_index + 1 :]
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token in {"--life", "--live"} and index + 1 < len(tokens):
            return tokens[index + 1]
        if token.startswith("--life="):
            return token.split("=", 1)[1]
        if token.startswith("--live="):
            return token.split("=", 1)[1]
        index += 1
    return None


def _normalize_quest_help_argv(argv: list[str] | None) -> list[str] | None:
    """Allow the convenient top-level ``quest --example/--schema`` spellings."""

    if argv is None:
        return None
    normalized = list(argv)
    try:
        index = normalized.index("quest")
    except ValueError:
        return normalized
    following = normalized[index + 1 :]
    if not following or following[0] in {"create", "list", "-h", "--help"}:
        return normalized
    if following[0] in {"--example", "--schema"}:
        normalized.insert(index + 1, "create")
    return normalized


