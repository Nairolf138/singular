def _systemd_quote(value: str) -> str:
    """Quote a value for systemd's EnvironmentFile syntax."""

    return (
        '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    )


def _atomic_write(path: Path, content: str, *, mode: int = 0o644) -> None:
    """Replace ``path`` atomically without exposing a partially written config."""

    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def _service_user_can_write(path: Path, user_name: str, group_name: str) -> bool:
    import grp
    import pwd

    user = pwd.getpwnam(user_name)
    group_ids = {user.pw_gid, grp.getgrnam(group_name).gr_gid}
    group_ids.update(g.gr_gid for g in grp.getgrall() if user_name in g.gr_mem)
    info = path.stat()
    permissions = stat.S_IMODE(info.st_mode)
    if info.st_uid == user.pw_uid:
        return bool(permissions & stat.S_IWUSR)
    if info.st_gid in group_ids:
        return bool(permissions & stat.S_IWGRP)
    return bool(permissions & stat.S_IWOTH)


def _install_systemd_service(
    root: Path,
    life: Path | None,
    *,
    user: str,
    group: str,
    binary: Path,
    environment_file: Path,
    unit_file: Path,
) -> int:
    """Validate one resolved context, persist it, and install its systemd unit."""

    import grp
    import pwd

    problems: list[str] = []
    if life is None or not life.is_dir():
        problems.append(
            "aucune vie active valide (exécutez `singular lives use <vie>`)"
        )
    if not binary.is_file():
        problems.append(f"binaire singular introuvable: {binary} (utilisez --binary)")
    valid_user = True
    valid_group = True
    try:
        pwd.getpwnam(user)
    except KeyError:
        valid_user = False
        problems.append(
            f"utilisateur de service inconnu: {user} (créez-le avec useradd)"
        )
    try:
        grp.getgrnam(group)
    except KeyError:
        valid_group = False
        problems.append(f"groupe de service inconnu: {group} (créez-le avec groupadd)")
    if life is not None:
        for directory in (life / "mem", life / "runs"):
            if not directory.is_dir():
                problems.append(f"répertoire requis absent: {directory}")
            elif valid_user and valid_group:
                if not _service_user_can_write(directory, user, group):
                    problems.append(
                        f"non inscriptible par {user}:{group}: {directory} "
                        f"(corrigez avec `chown -R {user}:{group} {root}`)"
                    )
    if problems:
        print(
            "Installation systemd annulée; le service serait inutilisable:",
            file=sys.stderr,
        )
        for problem in problems:
            print(f" - {problem}", file=sys.stderr)
        return 1

    assert life is not None
    values = {
        "SINGULAR_ROOT": str(root.resolve()),
        "SINGULAR_HOME": str(life.resolve()),
    }
    values.update(
        {
            name: os.environ[name]
            for name in _SYSTEMD_PROVIDER_ENV
            if os.environ.get(name)
        }
    )
    environment = (
        "# Generated by singular config root install-systemd; no secrets.\n"
        + "".join(f"{name}={_systemd_quote(value)}\n" for name, value in values.items())
    )
    template_path = (
        Path(__file__).resolve().parents[2] / "deploy/systemd/singular.service"
    )
    template = template_path.read_text(encoding="utf-8")
    unit = (
        template.replace("/etc/singular/singular.env", str(environment_file.resolve()))
        .replace("@SERVICE_USER@", user)
        .replace("@SERVICE_GROUP@", group)
        .replace("@SINGULAR_HOME@", str(life.resolve()))
        .replace("@SINGULAR_BINARY@", str(binary.resolve()))
    )
    _atomic_write(environment_file, environment, mode=0o640)
    _atomic_write(unit_file, unit)
    subprocess.run(["systemctl", "daemon-reload"], check=True)
    print(f"Contexte systemd: {environment_file}")
    print(f"Unité systemd: {unit_file} (vie active: {life})")
    return 0


def _path_unsupported_errors() -> tuple[type[Exception], ...]:
    """Return exception types raised when host-incompatible path classes are built."""

    errors: list[type[Exception]] = [NotImplementedError, RuntimeError]
    unsupported = getattr(getattr(pathlib, "_abc", None), "UnsupportedOperation", None)
    if isinstance(unsupported, type) and issubclass(unsupported, Exception):
        errors.append(unsupported)
    return tuple(dict.fromkeys(errors))


_PATH_UNSUPPORTED_ERRORS = _path_unsupported_errors()


