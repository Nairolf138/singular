def _recover_governance(*, operator: str, justification: str, emergency: bool) -> int:
    """Move open -> half_open -> closed only through an audited safe mutation probe."""
    from datetime import datetime, timezone

    from .governance.policy import (
        audit_circuit_transition,
        load_circuit_state,
        save_circuit_state,
    )
    from .life.loop import score_code_with_error

    home = Path(os.environ.get("SINGULAR_HOME", "."))
    state = load_circuit_state(home)
    old_state = str(state["state"])
    if old_state == "closed":
        print("Circuit déjà fermé; aucune remise à zéro effectuée.")
        return 0
    deadline = state.get("cooldown_deadline")
    cooldown_active = False
    if deadline:
        try:
            cooldown_active = datetime.now(timezone.utc) < datetime.fromisoformat(
                str(deadline)
            )
        except ValueError:
            cooldown_active = True
    diagnostics_ok = all(
        score_code_with_error(path.read_text(encoding="utf-8")).ok
        for path in _iter_sandbox_skill_files(home / "skills")
    )
    if (cooldown_active or not diagnostics_ok) and not emergency:
        reason = (
            "cooldown non échu"
            if cooldown_active
            else "cause non corrigée (diagnostic sandbox KO)"
        )
        print(
            f"Reset refusé: {reason}. Utilisez --emergency uniquement avec justification auditée.",
            file=sys.stderr,
        )
        return 1
    now = datetime.now(timezone.utc).isoformat()
    state.update({"state": "half_open", "updated_at": now})
    save_circuit_state(state, home)
    audit_circuit_transition(
        home=home,
        operator=operator,
        justification=justification,
        old_state=old_state,
        new_state="half_open",
        emergency=emergency,
        evidence={
            "diagnostics_corrected": diagnostics_ok,
            "cooldown_active": cooldown_active,
        },
    )
    probe = score_code_with_error("result = 1\n")
    state["last_probe"] = {
        "timestamp": now,
        "kind": "low_risk_mutation",
        "success": probe.ok,
        "error_type": probe.error_type,
    }
    new_state = "closed" if probe.ok else "open"
    state["state"] = new_state
    if probe.ok:
        state["closure_decision"] = {
            "timestamp": now,
            "decision": "closed_after_successful_probe",
            "operator": operator,
            "justification": justification,
        }
    save_circuit_state(state, home)
    audit_circuit_transition(
        home=home,
        operator=operator,
        justification=justification,
        old_state="half_open",
        new_state=new_state,
        emergency=emergency,
        evidence={"probe": state["last_probe"]},
    )
    print(
        f"Sonde à faible risque: {'succès' if probe.ok else 'échec'}; circuit {new_state}."
    )
    return 0 if probe.ok else 1


def _doctor_fix_windows_user_path(scripts_path: Path) -> bool:
    """Add scripts_path to the Windows user Path variable when missing."""

    if os.name != "nt":
        print("⚠️ `doctor --fix` non supporté sur cette plateforme.")
        return False

    import winreg as _winreg

    winreg: Any = _winreg

    target = str(scripts_path)
    target_norm = _normalize_windows_path_entry(target)

    with winreg.OpenKey(
        winreg.HKEY_CURRENT_USER,
        "Environment",
        0,
        winreg.KEY_READ | winreg.KEY_SET_VALUE,
    ) as key:
        try:
            raw_user_path, _ = winreg.QueryValueEx(key, "Path")
        except FileNotFoundError:
            raw_user_path = ""

        entries = [entry for entry in raw_user_path.split(";") if entry.strip()]
        deduped_entries: list[str] = []
        seen: set[str] = set()
        for entry in [*entries, target]:
            normalized = _normalize_windows_path_entry(entry)
            if not normalized or normalized in seen:
                continue
            deduped_entries.append(entry.strip())
            seen.add(normalized)

        if target_norm in {_normalize_windows_path_entry(entry) for entry in entries}:
            print("✅ Le dossier Scripts est déjà présent dans le Path utilisateur.")
            print("➡️ Pensez à redémarrer PowerShell pour recharger l'environnement.")
            return False

        new_user_path = ";".join(deduped_entries)
        winreg.SetValueEx(key, "Path", 0, winreg.REG_EXPAND_SZ, new_user_path)

    print("✅ Le dossier Scripts a été ajouté au Path utilisateur Windows.")
    print("➡️ Veuillez redémarrer PowerShell pour appliquer ce changement.")
    return True


